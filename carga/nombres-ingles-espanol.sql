-- 1 · La galería: lo que está en `nombre` es el inglés → pasa a `alias`; lo
--     que había en `alias` (palabras de búsqueda) → `busqueda`; y `nombre`
--     queda en español.
--     (Las de tus rutinas no entran aquí: su `nombre` ya está en español.)
update ejercicios e
   set busqueda   = coalesce(nullif(e.busqueda, ''),
                             case when pg_temp.ecm_norm(e.alias) <> pg_temp.ecm_norm(e.nombre) then nullif(e.alias, '') end),
       alias      = e.nombre,   -- el inglés tal cual estaba
       nombre     = t.es,
       updated_at = now()
  from _tr t
 where pg_temp.ecm_norm(e.nombre) = pg_temp.ecm_norm(t.en)
   -- ya hecha (inglés en alias y su traducción en nombre): no se toca otra vez
   and (e.alias is null
        or pg_temp.ecm_norm(e.alias) <> pg_temp.ecm_norm(e.nombre)
        or pg_temp.ecm_norm(e.nombre) <> pg_temp.ecm_norm(t.es));

-- 2 · Las de tus rutinas (ya en español): solo las palabras de búsqueda.
update ejercicios e
   set busqueda = k.kw, updated_at = now()
  from _kw k
 where pg_temp.ecm_norm(e.alias) = pg_temp.ecm_norm(k.en)
   and coalesce(e.busqueda, '') = ''
   and pg_temp.ecm_norm(k.kw) <> pg_temp.ecm_norm(e.alias);

-- Cómo quedó: cuántas fichas tienen inglés + español, y las que no.
select count(*) filter (where alias is not null and pg_temp.ecm_norm(alias) <> pg_temp.ecm_norm(nombre)) as con_ingles_y_espanol,
       count(*) filter (where alias is null or pg_temp.ecm_norm(alias) = pg_temp.ecm_norm(nombre))      as con_un_solo_nombre,
       count(*) as total
  from ejercicios where not coalesce(archivado, false);

