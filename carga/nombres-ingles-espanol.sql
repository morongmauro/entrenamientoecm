-- Dónde: Supabase del CRM → SQL Editor → pegar todo → Run.
-- Se puede correr dos veces: la segunda no cambia nada.
--
-- El problema: las fichas estaban guardadas de dos maneras.
--   · Las ~240 que vinieron en tus rutinas de Trainerize: `nombre` en español
--     y el original de Trainerize en `alias`. Bien.
--   · Las ~2.000 de la galería (la librería completa de Trainerize): `nombre`
--     en INGLÉS, sin traducir, y en `alias` unas palabras de búsqueda de
--     Trainerize. Por eso en el CRM unas salían en español y otras en inglés.
--
-- Después de esto TODAS quedan igual:
--   alias    = el nombre exacto de Trainerize (inglés) → se ve grande, y es
--              con el que se reconocen las rutinas y los videos. No se toca.
--   nombre   = la traducción al español → se ve debajo, chico.
--   busqueda = las palabras de búsqueda de Trainerize (columna nueva), para
--              que el buscador del CRM las siga encontrando.
--
-- Solo cambia las fichas cuyo `nombre` es todavía el inglés de la galería
-- (1976 traducciones). Las tuyas en español no se tocan; a las de tus
-- rutinas solo se les añaden las palabras de búsqueda.
